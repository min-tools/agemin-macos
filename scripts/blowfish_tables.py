# Compute the hex digits of pi with Machin's formula and write Blowfish's P-array and S-boxes as
# Swift source to the file named on the command line.
import sys
# Blowfish needs 18 P words and four 256-word S-boxes; the guard digits absorb rounding error.
WORDS = 18 + 4 * 256
HEX_DIGITS = WORDS * 8
GUARD = 64
BITS = (HEX_DIGITS + GUARD) * 4
ONE = 1 << BITS

# arctan_inv(x): Return arctan(1/x) scaled by ONE, summed from the Taylor series.
def arctan_inv(x):
    total = term = ONE // x
    x2 = x * x
    n = 1
    sign = -1
    # Each term shrinks by x^2; stop once it underflows to zero.
    while term:
        term //= x2
        n += 2
        total += sign * (term // n)
        sign = -sign
    return total

pi = 16 * arctan_inv(5) - 4 * arctan_inv(239)
# Drop the integer part (3) and keep the fractional hex digits.
frac = pi - 3 * ONE
digits = format(frac, 'x').rjust(BITS // 4, '0')[:HEX_DIGITS]
# Cut the digits into 32-bit words: 18 for P, then 256 for each S-box in order.
words = [int(digits[i:i + 8], 16) for i in range(0, HEX_DIGITS, 8)]
P = words[:18]
S = [words[18 + i * 256: 18 + (i + 1) * 256] for i in range(4)]
# Known Blowfish constants from the reference implementation.
assert P[0] == 0x243F6A88 and P[1] == 0x85A308D3 and P[2] == 0x13198A2E and P[3] == 0x03707344, P[:4]
assert P[17] == 0x8979FB1B, hex(P[17])
assert S[0][0] == 0xD1310BA6 and S[0][1] == 0x98DFB5AC, [hex(v) for v in S[0][:2]]
assert S[3][255] == 0x3AC372E6, hex(S[3][255])
print('ok', hex(P[0]), hex(P[17]), hex(S[0][0]), hex(S[3][255]))
# Emit the Swift enum, six words per line so the generated file stays readable.
with open(sys.argv[1], 'w') as out:
    out.write('// Blowfish initial state: the fractional hexadecimal digits of pi, as the cipher\n')
    out.write('// specifies. Generated by scripts/blowfish_tables.py; do not edit by hand.\n')
    out.write('enum BlowfishTables {\n')
    out.write('    static let p: [UInt32] = [\n')
    for i in range(0, 18, 6):
        out.write('        ' + ', '.join(f'0x{v:08X}' for v in P[i:i + 6]) + ',\n')
    out.write('    ]\n\n')
    out.write('    static let s: [[UInt32]] = [\n')
    for box in S:
        out.write('        [\n')
        for i in range(0, 256, 6):
            out.write('            ' + ', '.join(f'0x{v:08X}' for v in box[i:i + 6]) + ',\n')
        out.write('        ],\n')
    out.write('    ]\n}\n')
